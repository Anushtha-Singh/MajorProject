import requests
from bs4 import BeautifulSoup

url = "https://www.india.gov.in/news_feeds?rand=1742633241721"
headers = {"User-Agent": "Mozilla/5.0"}  # Server block na kare

response = requests.get(url, headers=headers)

if response.status_code == 200:
    soup = BeautifulSoup(response.text, "html.parser")

    # Sabhi news links extract karein
    news_items = soup.find_all("li", class_="views-row")

    for news in news_items:
        title = news.find("a").text.strip()  # News title
        link = news.find("a")["href"]  # News link
        print(f"📰 {title}: {link}")
else:
    print("❌ Failed to fetch news data!")

