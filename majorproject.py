import json

# JSON File Load Karna
with open("pmkisan_data.json", "r", encoding="utf-8") as file:
    data = json.load(file)

# Features ke andar ka data extract karna
features = data.get("features", [])

# State-wise data store karne ke liye dictionary
state_data = {}

# Har feature ko check karna
for feature in features:
    properties = feature.get("properties", {})
    state_name = properties.get("STNAME", "Unknown")
    state_code = properties.get("STCODE11", "Unknown")

    # Data ko store karna
    state_data[state_name] = {
        "State Code": state_code,
        "LGD Code": properties.get("State_LGD", "Unknown")
    }

# Extracted Data Print Karna
for state, details in state_data.items():
    print(f"State: {state}")
    print(f"  State Code: {details['State Code']}")
    print(f"  LGD Code: {details['LGD Code']}")
    print("-" * 40)

